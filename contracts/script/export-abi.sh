#!/usr/bin/env bash
# Regenerates shared/abi/TabEscrow.{json,ts} from the compiled artifact. Run after any interface change.
set -euo pipefail
export PATH="$HOME/.foundry/bin:$PATH"
cd "$(dirname "$0")/.."
forge build --silent
out=../shared/abi
mkdir -p "$out"
jq '.abi' out/TabEscrow.sol/TabEscrow.json > "$out/TabEscrow.json"
{
  echo "// Generated by contracts/script/export-abi.sh. Do not edit by hand."
  printf 'export const tabEscrowAbi = %s as const;\n' "$(cat "$out/TabEscrow.json")"
} > "$out/TabEscrow.ts"
echo "wrote $out/TabEscrow.json and $out/TabEscrow.ts"
